"""A test-only SEG-Y writer, copying RadExplorer's layout (spec M21 §2, §15).

Big-endian, picosecond times, float32 samples, the geographic flag written
little-endian, and each trace optionally pushed down by a static and padded
with zeros, as RadExplorer exports it. It never writes a real coordinate:
geographic flags are set with the coordinate bytes left zero.

Synthetic files prove self-consistency only; the real files in
`tests/data/local/segy` catch real quirks.
"""

from __future__ import annotations

import struct
from collections.abc import Mapping, Sequence
from pathlib import Path

import numpy as np

RADEXPLORER_TEXT = (
    "This file contains GPR data and was generated by RadExplorer software. It has few "
    "modifications to standard SEG-Y: 1.\tAll time-based values (i.e. sample interval and "
    "delay) are represented in PICOsecons, not in MICROsecons or MILLIseconds. 2.\tAny trace "
    "may have so-called mark - an integer number. This mark is placed into 239-240 bytes of "
    "the Trace Header. When a trace has a mark, bytes 237-238 contain a mark indicator equal "
    "to 55H. 3.\tThe coordinates (stored in standard SEG-Y fields, bytes 73-88) are always "
    "supposed to be measured in either meters or arc seconds. 4.\tThe geographic coordinates, "
    "when available, are saved to bytes 229-232 (longitude) and 233-236 (latitude)."
)
OTHER_TEXT = "C 1 CLIENT                        COMPANY                       CREW NO"


def _text(text: str, ascii_text: bool) -> bytes:
    cards = text.ljust(80 * 38) + "C39 SEG Y REV0".ljust(80) + "C40 END EBCDIC".ljust(80)
    return cards[:3200].encode("latin-1" if ascii_text else "cp500")


def write_segy(
    path: Path,
    data: np.ndarray,
    *,
    dt_ps: int = 406,
    delay_ps: int = 11766,
    x_mm: Sequence[int] | None = None,
    y_mm: Sequence[int] | None = None,
    scalar: int = -1000,
    units: int = 1,
    statics_ns: Sequence[int] | None = None,
    shifts: Sequence[int] | None = None,
    stored_samples: int | None = None,
    text: str = RADEXPLORER_TEXT,
    ascii_text: bool = False,
    format_code: int = 5,
    little_endian: bool = False,
    extended: int = 0,
    geographic: bool = True,
    trace_samples: Mapping[int, int] | None = None,
    trace_dt: Mapping[int, int] | None = None,
    delays: Mapping[int, int] | None = None,
    positions: np.ndarray | None = None,
) -> Path:
    """Write `data` (n_samples, n_traces) as a RadExplorer-style SEG-Y at `path`.

    `x_mm` and `y_mm` are the stored coordinate integers (millimetres with the
    default scalar of -1000); X defaults to 68 per trace and Y to 0.
    `statics_ns` writes each trace `round(static / dt)` samples down, padded
    with zeros; `shifts` overrides those sample counts, to make the zeros and
    the static disagree. `stored_samples` defaults to the data plus the largest
    shift. `trace_samples`, `trace_dt` and `delays` override one trace's word
    (`{index: value}`). `little_endian` writes the binary header's words
    little-endian. `positions` is (n_traces, 2) of made-up (lon, lat) degrees,
    written x 10^6 little-endian with the geographic flag set; without it the
    flag follows `geographic` and the coordinate bytes stay zero.
    """
    path = Path(path)
    data = np.asarray(data, dtype=np.float32)
    n_samples, n_traces = data.shape
    statics = list(statics_ns) if statics_ns is not None else [0] * n_traces
    if shifts is None:
        shifts = [round(s * 1000 / dt_ps) if s else 0 for s in statics]
    shifts = list(shifts)
    stored = stored_samples if stored_samples is not None else n_samples + max(shifts, default=0)
    xs = list(x_mm) if x_mm is not None else [68 * i for i in range(n_traces)]
    ys = list(y_mm) if y_mm is not None else [0] * n_traces
    trace_samples = trace_samples or {}
    trace_dt = trace_dt or {}
    delays = delays or {}

    binary = bytearray(400)
    order = "<" if little_endian else ">"
    struct.pack_into(f"{order}h", binary, 16, dt_ps)
    struct.pack_into(f"{order}h", binary, 20, stored)
    struct.pack_into(f"{order}h", binary, 24, format_code)
    struct.pack_into(">h", binary, 304, extended)

    out = bytearray(_text(text, ascii_text) + bytes(binary))
    for i in range(n_traces):
        head = bytearray(240)
        delay = delays.get(i, delay_ps)
        struct.pack_into(">i", head, 0, i)
        struct.pack_into(">i", head, 4, i)
        struct.pack_into(">h", head, 70, scalar)
        struct.pack_into(">i", head, 72, xs[i])
        struct.pack_into(">i", head, 76, ys[i])
        struct.pack_into(">h", head, 88, units)
        struct.pack_into(">h", head, 100, statics[i])
        struct.pack_into(">h", head, 106, -delay)
        struct.pack_into(">h", head, 108, delay)
        struct.pack_into(">h", head, 114, trace_samples.get(i, stored))
        struct.pack_into(">h", head, 116, trace_dt.get(i, dt_ps))
        if positions is not None:
            struct.pack_into("<h", head, 226, 1)
            struct.pack_into("<i", head, 228, round(positions[i][0] * 1e6))
            struct.pack_into("<i", head, 232, round(positions[i][1] * 1e6))
        else:
            struct.pack_into("<h", head, 226, 1 if geographic else 0)
        trace = np.zeros(stored, dtype=">f4")
        end = min(stored, shifts[i] + n_samples)
        trace[shifts[i] : end] = data[: end - shifts[i], i]
        out += head + trace.tobytes()
    path.write_bytes(bytes(out))
    return path
